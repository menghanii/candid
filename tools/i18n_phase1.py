def main():
  out = {'en': {}, 'ja': {}}
  for ko, en, ja in P:
    out['en'][ko] = en; out['ja'][ko] = ja
  (ROOT / 'i18n').mkdir(exist_ok=True)
  for lang, d in out.items():
    path = ROOT / 'i18n' / f'{lang}.js'
    old = {}
    if path.exists():  # 기존 사전과 합침(2·3단계에서 추가해도 유지)
      m = re.search(r'=\s*(\{.*\});?\s*$', path.read_text(), re.S)
      if m: old = json.loads(m.group(1))
    old.update(d)
    body = json.dumps(old, ensure_ascii=False, indent=1)
    path.write_text(f"// candid. {lang} 번역 사전 — 키는 한국어 원문. tools/i18n-check.js 로 빠진 문구 확인\n(window.CANDID_I18N = window.CANDID_I18N || {{}}).{lang} = {body};\n")
  print('dict ok', len(P))

if __name__ == '__main__':
  main()
